import { DASH } from './_jalur.mjs'
const { tebakFungsi, validasiFungsi } = await import(DASH + '/server/src/utils/fungsi.js')
let gagal = 0
const rupa = (h) => h.map(x => x.fungsi + (x.bidang ? `(${x.bidang})` : '')).sort().join('+') || '—'
const cek = (posisi, peran, harap) => { const r = rupa(tebakFungsi(posisi, peran)); const ok = r === harap; if (!ok) gagal++; console.log(`${ok ? '✅' : '❌'} "${posisi ?? ''}" [${peran}] → ${r}${ok ? '' : `   (harapan ${harap})`}`) }
console.log('— posisi nyata dari data Ekosistem —')
cek('3D Artist', 'KARYAWAN', 'ARTIST(3D)')
cek('Rigger', 'KARYAWAN', 'ARTIST(Rigging)')
cek('Illustrator', 'KARYAWAN', 'ARTIST(Ilustrasi)')
cek('Ilustrator', 'KARYAWAN', 'ARTIST(Ilustrasi)')
cek('Animator', 'KARYAWAN', 'ARTIST(Animasi)')
cek('Designer', 'KARYAWAN', 'ARTIST(Desain)')
cek('Designer Graphic', 'KARYAWAN', 'ARTIST(Desain)')
cek('Admin', 'KARYAWAN', 'MARKETER')
cek('admin', 'KARYAWAN', 'MARKETER')
cek('Admin Vgen', 'KARYAWAN', 'MARKETER')
cek('Admin VGen', 'KARYAWAN', 'MARKETER')
cek('Admin LTK', 'KARYAWAN', 'MARKETER')
cek('Admin Marketing', 'KARYAWAN', 'MARKETER')
cek('Admin-Illustrator', 'KARYAWAN', 'ARTIST(Ilustrasi)+MARKETER')
cek('Karyawan/Rigger&Animator', 'KARYAWAN', 'ARTIST(Rigging,Animasi)')
cek('Rigger/Animator Magang', 'MAGANG', 'ARTIST(Rigging,Animasi)')
cek('Magang Illustrator', 'MAGANG', 'ARTIST(Ilustrasi)')
cek('Magang 3D Artist', 'MAGANG', 'ARTIST(3D)')
cek('Magang/Rigger', 'MAGANG', 'ARTIST(Rigging)')
cek('Rigger Magang', 'MAGANG', 'ARTIST(Rigging)')
cek('Koordinator', 'KOORDINATOR', 'PM_QC')
cek('Head Production', 'KARYAWAN', 'PM_QC')
cek('Project Manager', 'KARYAWAN', 'PM_QC')
cek('Produksi', 'KARYAWAN', 'ARTIST')
console.log('— kasus tepi —')
cek('', 'KARYAWAN', '—'); cek(null, 'MAGANG', '—'); cek('Magang', 'MAGANG', '—'); cek('maggang', 'MAGANG', '—')
cek('Karyawan', 'KARYAWAN', '—')
cek('Illustrator', 'KOORDINATOR', 'ARTIST(Ilustrasi)+PM_QC')
cek('', 'KOORDINATOR', 'PM_QC')
console.log('— validasi isian koordinator —')
const v = (d) => validasiFungsi(d)
const t = (l, ok) => { if (!ok) gagal++; console.log(`${ok ? '✅' : '❌'} ${l}`) }
t('Isian sah → daftar bersih', v([{ fungsi: 'ARTIST', bidang: '3D' }, { fungsi: 'MARKETER' }]).daftar?.length === 2)
t('Dua bidang artist diterima & diurutkan', v([{ fungsi: 'ARTIST', bidang: 'Animasi,Rigging' }]).daftar?.[0]?.bidang === 'Rigging,Animasi')
t('Fungsi ganda digabung', v([{ fungsi: 'MARKETER' }, { fungsi: 'MARKETER' }]).daftar?.length === 1)
t('Fungsi tak dikenal ditolak', !!v([{ fungsi: 'DUKUN' }]).galat)
t('Bidang tak dikenal ditolak', !!v([{ fungsi: 'ARTIST', bidang: 'Memasak' }]).galat)
t('Bidang pada non-artist ditolak', !!v([{ fungsi: 'MARKETER', bidang: '3D' }]).galat)
t('Bukan daftar ditolak', !!v('ARTIST').galat)
console.log(`\ngagal: ${gagal}`); process.exit(gagal ? 1 : 0)
